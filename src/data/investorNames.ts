export function splitInvestorName(full: string) {
  if (full.includes(' – ')) {
    const [name, subtitle] = full.split(' – ')
    return { name, subtitle }
  }
  const [name, ...rest] = full.split(' - ')
  return { name, subtitle: rest.join(' - ') }
}
